export const messages = { zh, en };

export type Messages = typeof zh;

export function translate(source: Messages, path: string, values?: Record<string, string | number>) {
  const value = path.split(".").reduce<unknown>((acc, part) => {
    if (acc && typeof acc === "object" && part in acc) return (acc as Record<string, unknown>)[part];
    return undefined;
  }, source);
  let text = typeof value === "string" ? value : path;
  if (values) {
    for (const [key, item] of Object.entries(values)) text = text.replaceAll(`{${key}}`, String(item));
  }
  return text;
}
